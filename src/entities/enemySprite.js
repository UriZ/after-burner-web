// ---------------------------------------------------------------------------
// A MISSING SHEET IS LOUD. (R5 judge, "what nobody had looked at", second
// finding.) The old handler was
//
//     () => { /* decode failure: stay absent, procedural fallback holds */ }
//
// -- no error, no warning, and the procedural drawing renders in its place.
// That silence is a determinism hazard for every judge capture, because a
// capture that steps before the images decode gets different art with no
// signal at all; it is also the most likely reason a wrong enemy colour
// survived a full round unnoticed. Three things now happen instead:
//
//   1. a decode failure logs console.error once, naming the key and the URL;
//   2. every enemyTexture() call that falls through to the procedural path
//      is COUNTED, and the first one per (livery, aspect, night, detail)
//      combination logs console.warn;
//   3. window.__spriteSheetStatus() reports loaded / failed / pending and the
//      full fallback census, so a capture or probe can assert zero rather
//      than infer it from pixels.
//
// The far LOD is a deliberate, declared exception and is NOT counted as a
// fallback -- see the note on enemyTexture().
// ---------------------------------------------------------------------------
const sheetFailures = new Map(); // key -> url, for sheets that failed to decode
const proceduralUses = new Map(); // combination key -> count

function noteProceduralUse(key, why) {
  const prev = proceduralUses.get(key) ?? 0;
  proceduralUses.set(key, prev + 1);
  if (prev === 0 && typeof console !== 'undefined') {
    console.warn(
      `[enemySprite] PROCEDURAL FALLBACK for ${key} (${why}). The authored ` +
      'sheet is not in use for this enemy; art will differ from the ' +
      'redrawn silhouette. See window.__spriteSheetStatus().'
    );
  }
}

function loadSheetImage(key, url) {
  const loader = new THREE.ImageLoader();
  loader.load(
    url,
    (image) => { sheetImages.set(key, image); },
    undefined,
    () => {
      sheetFailures.set(key, url);
      if (typeof console !== 'undefined') {
        console.error(`[enemySprite] SHEET DECODE FAILED: ${key} <- ${url}. ` +
          'Falling back to procedural art for every enemy in that ' +
          'combination. This is a bug, not a graceful degradation.');
      }
    }
  );
}
for (const [key, url] of Object.entries(SHEET_URLS)) loadSheetImage(key, url);

if (typeof window !== 'undefined') {
  // POSITIVE CONTROL for the census below. CLAUDE.md: "validate the instrument
  // on a known input before trusting any number", and a counter that reports
  // zero is exactly the kind of clean, plausible, stable number this project
  // has been burned by. This asks for a texture under a livery key that has no
  // sheet, which is the same code path a decode failure takes, and checks that
  // the counter moved. It restores the counter afterwards so running the
  // control does not contaminate the census.
  window.__spriteSheetSelfTest = () => {
    const probeKey = 'headOn|__selftest__|detail|day';
    const before = proceduralUses.get(probeKey) ?? 0;
    enemyTexture('headOn', '__selftest__', true, false, 0);
    const after = proceduralUses.get(probeKey) ?? 0;
    proceduralUses.delete(probeKey);
    cache.delete('headOn|__selftest__|true|false');
    return { detected: after === before + 1, before, after };
  };
  window.__spriteSheetStatus = () => ({
    expected: Object.keys(SHEET_URLS).length,
    loaded: [...sheetImages.keys()].sort(),
    failed: Object.fromEntries(sheetFailures),
    pending: Object.keys(SHEET_URLS).filter(
      (k) => !sheetImages.has(k) && !sheetFailures.has(k)
    ),
    proceduralUses: Object.fromEntries(proceduralUses),
    proceduralTotal: [...proceduralUses.values()].reduce((a, b) => a + b, 0),
  });
}

// Crops one cell out of a loaded sheet image into its own hard-edged
// texture (nearest-neighbour `drawImage`, integer cell boundaries -- no
// resampling blur). Cached per (livery, aspect, night, cellIndex).
function sheetCellTexture(livery, aspect, night, cellIndex) {
  const sheetKey = `${livery}|${aspect}|${night ? 'night' : 'day'}`;
  const key = `${sheetKey}|${cellIndex}`;
  let tex = sheetCellCache.get(key);
  if (tex) return tex;
  const image = sheetImages.get(sheetKey);
  if (!image) return null;

  const canvas = document.createElement('canvas');
  canvas.width = SHEET_CELL_W;
  canvas.height = SHEET_CELL_H;
  const ctx = canvas.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(
    image,
    cellIndex * SHEET_CELL_W, 0, SHEET_CELL_W, SHEET_CELL_H,
    0, 0, SHEET_CELL_W, SHEET_CELL_H
  );
  tex = new THREE.CanvasTexture(canvas);
  tex.magFilter = THREE.NearestFilter;
  tex.minFilter = THREE.NearestFilter;
  tex.colorSpace = THREE.SRGBColorSpace;
  tex.generateMipmaps = false;
  sheetCellCache.set(key, tex);
  return tex;
}

function nearestBankIndex(bankDeg) {
  let best = 0;
  let bestDist = Infinity;
  SHEET_BANK_ANGLES.forEach((a, i) => {
    const dist = Math.abs(a - bankDeg);
    if (dist < bestDist) {
      bestDist = dist;
      best = i;
    }
  });
  return best;
}

// R5 interfaces I1 (approved): the enemy livery API combatfx-r5 is blocked
// on. `aspect`: 'headOn' | 'rear'. `livery`: a key of LIVERIES. `detail`:
// true = near (64x32) texture, false = far (16x8) LOD. `night`: palette
// swap per-livery (REFERENCE.md "Night palette swap" / I3). `bankDeg`:
// signed bank angle in degrees, used to pick one of the sheet's five poses.
//
// R6: EVERY `detail` combination is authored art now -- 4 liveries x 2
// aspects x day/night = 16 sheets. The procedural detail drawing below is no
// longer a design, it is an alarm: reaching it means a sheet failed to decode
// or has not decoded yet, and it says so (noteProceduralUse).
//
// THE FAR LOD IS A DECLARED EXCEPTION, not an oversight, and it is the one
// place I did not follow judge gap 2's "either author a sheet or make the
// procedural path draw the same silhouette". Both halves of that are wrong
// here, and the reason is in the long comment above drawHeadOnFar(): at 3-9
// native px the sprite is 1-4 screen ROWS tall, any transparent row is a
// frame where the aircraft vanishes (measured: 27 of 80 frames of one
// approach rendered zero pixels), and the fix was a FULLY OPAQUE texture that
// reads by value rather than by shape. Drawing "the same silhouette" there
// reintroduces that bug, and the gap's own reproduction is specified at
// >=15 %W -- about 48 native px, nearly five times the 10 px detail switch --
// so the four silhouette criteria are not measurable in the far band at all.
// What the far LOD genuinely needed was to stop being a second, drifting copy
// of the palette; it now draws from the generated module, so near and far,
// day and night cannot disagree on a colour. Fallbacks here are therefore NOT
// counted by noteProceduralUse. See judging/R6/lane-sprite-art.md.
//
// Memoised per (aspect, livery, detail, night) for the procedural path; the
// sheet path has its own per-cell cache.
export function enemyTexture(aspect, livery = 'grey', detail = true, night = false, bankDeg = 0, flare = false) {
  // Authored art for EVERY near combination: four liveries x two aspects x
  // day and night. R5's gate was `if (detail && !night)`, which is the whole
  // of judge gap 2.
  if (detail) {
    // R37: the rear sheet's flared row lives at cellIndex + 9 (see
    // SHEET_BANK_ANGLES / REAR_FLARE_STATES above). `flare` is ignored for
    // head sheets, which have no second row.
    const flareOffset =
      aspect === 'rear' && flare ? SHEET_BANK_ANGLES.length : 0;
    const cellTex = sheetCellTexture(
      livery, aspect, night, nearestBankIndex(bankDeg) + flareOffset);
    if (cellTex) return cellTex;
    noteProceduralUse(
      `${aspect}|${livery}|detail|${night ? 'night' : 'day'}`,
      sheetFailures.has(`${livery}|${aspect}|${night ? 'night' : 'day'}`)
        ? 'sheet failed to decode'
        : 'sheet not decoded yet'
    );
  }

  const key = `${aspect}|${livery}|${detail}|${night}`;
  let tex = cache.get(key);
  if (tex) return tex;

  const pal = resolvePalette(livery, night);
  if (detail) {
    const drawFn = aspect === 'rear' ? drawRear : drawHeadOn;
    tex = buildTexture(drawFn, W, H, pal);
  } else {
    const drawFn = aspect === 'rear' ? drawRearFar : drawHeadOnFar;
    // No keyline on the far LOD: every texel is already opaque (the
    // invariant above), so there is no boundary to outline.
    tex = buildTexture(drawFn, FW, FH, pal, { keyline: false, far: true });
  }
  cache.set(key, tex);
  return tex;
}

