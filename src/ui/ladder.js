// The Sega hardware colour ladder, at RUNTIME.
//
// WHY THIS FILE EXISTS, AND WHY IT IS NOT AN IMPORT OF tools/art/ladder.js.
// `tools/art/ladder.js` is the offline sheet generators' gate: it runs at
// authoring time, over `tools/art/palettes.js`, and nothing it guards ships
// in the bundle. Everything in this directory and in `game/flow/` authors its
// colours as inline hex constants that no generator ever sees, and R7's
// per-object census found exactly that gap: the three surfaces with no
// generator behind them (title screen, tally/READY/continue cards, death
// hulk) were the three carrying every off-ladder channel value in the build.
// So the gate has to exist on the runtime side too. Importing the tools file
// into `src/` would pull authoring code into the game bundle; the table is 31
// integers and `tools/out/ladder-r8/inst.py --selftest` asserts the two
// copies are identical, so the duplication is checked rather than trusted.
//
// THE TABLE IS NOT GENERATED BY FORMULA. REFERENCE.md "The ladder,
// enumerated": `round(k*255/31)` yields 90 where the arcade has 91 and 165
// where it has 164, and emits 8, which appears in neither native frame. The
// hardware drives each channel through a resistor ladder, not a linear DAC.
// Snap to the table; never to a formula.
//
// WHAT LADDER MEMBERSHIP BUYS, which is the whole reason this is worth
// enforcing: Criterion A2 is `|union of the three channels' value sets| <= 32`.
// The ladder has 31 members. **A frame whose every pixel is on the ladder
// cannot exceed 31**, so A2 becomes structurally satisfied rather than
// something to measure and hope about. Stage 1's sky `#009fff` (channel 159)
// is the one deliberate exception in this build — the arcade's own measured
// stage-1 sky `#009eff` is 158, equally off the ladder (REFERENCE.md: there
// is no native stage-1 frame, so the value carries the video chain's level
// expansion on both sides). That costs exactly one value, so stage 1 lands at
// 32 and stages 2-3 at 31. Do not "fix" 159.
export const LADDER = [
  0, 16, 25, 33, 41, 49, 58, 66, 74, 82, 91, 99, 107, 115, 123, 132, 140, 148,
  156, 164, 173, 181, 189, 197, 206, 214, 222, 230, 239, 247, 255,
];

const LADDER_SET = new Set(LADDER);

export function isOnLadder(v) {
  return LADDER_SET.has(v);
}

export function nearestLadderValue(v) {
  let best = LADDER[0];
  let bestDist = Math.abs(v - best);
  for (const l of LADDER) {
    const d = Math.abs(v - l);
    if (d < bestDist) {
      best = l;
      bestDist = d;
    }
  }
  return best;
}

export function hexToRgb(hex) {
  const h = hex.replace('#', '');
  return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
}

export function rgbToHex(r, g, b) {
  const h = (n) => n.toString(16).padStart(2, '0');
  return `#${h(r)}${h(g)}${h(b)}`;
}

/** ASSERT THE INPUTS, NOT THE OUTPUT (REFERENCE.md's binding process rule,
 * earned by the R7 sprite lane's silent-erasure bug: four count-based gates
 * passed a sheet with holes punched in it). This throws at module load on the
 * authored constant, naming it, rather than letting a capture come back one
 * channel value over the gate and leaving the next lane to find out which of
 * forty colours did it. A throw at module scope is deliberately loud:
 * tools/capture.mjs collects page errors and exits non-zero, so a bad palette
 * constant fails every capture in the round instead of quietly costing it. */
export function assertOnLadder(hexes, label) {
  for (const hex of hexes) {
    const [r, g, b] = hexToRgb(hex);
    if (!isOnLadder(r) || !isOnLadder(g) || !isOnLadder(b)) {
      const nearest = rgbToHex(nearestLadderValue(r), nearestLadderValue(g), nearestLadderValue(b));
      throw new Error(
        `[ladder] ${label}: ${hex} is off the Sega ladder (nearest: ${nearest}). ` +
        'Criterion A2 is |union of channel values| <= 32 and the ladder has 31 members, ' +
        'so one off-ladder constant is one value of the frame-wide budget. Fix the constant.'
      );
    }
  }
}
