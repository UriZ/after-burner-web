// Build-all entry point for authored sprite sheets. Each sheet module
// exports a build*Sheet() function returning a PixelCanvas; this script
// writes the sheet to src/assets/sprites/ and a nearest-neighbour zoomed
// copy to tools/out/art-zoom/ for visual inspection against reference/.
import { buildPlayerF14Sheet } from './sheets/player-f14.js';
import {
  buildEnemySheet,
  ENEMY_SHEET_LIVERIES,
  ENEMY_SHEET_ASPECTS,
  ENEMY_SHEET_NIGHT,
} from './sheets/enemy-mig.js';
import { ENEMY_LIVERIES } from './palettes.js';
import { writeFileSync } from 'node:fs';
import { buildExplosionSheet } from './sheets/explosion.js';
import { buildFontSheet } from './sheets/font.js';
import { buildExplosionBigSheet } from './sheets/explosion-big.js';
import { buildDebrisSheet } from './sheets/debris.js';
import { buildSmokePuffSheet } from './sheets/smoke-puff.js';
import { buildMissileSheet } from './sheets/missile.js';
import { buildPlayerF14NightSheet } from './sheets/player-f14-night.js';
import { buildPlayerF14RollSheet } from './sheets/player-f14-roll.js';

const OUT_DIR = new URL('../../src/assets/sprites/', import.meta.url).pathname;
const ZOOM_DIR = new URL('../out/art-zoom/', import.meta.url).pathname;

const SHEETS = {
  'player-f14.png': { build: buildPlayerF14Sheet, zoom: 8 },
  'explosion.png': { build: buildExplosionSheet, zoom: 6 },
  'font-5x7.png': { build: buildFontSheet, zoom: 8 },
  'explosion-big.png': { build: buildExplosionBigSheet, zoom: 3 },
  'debris.png': { build: buildDebrisSheet, zoom: 20 },
  'smoke-puff.png': { build: buildSmokePuffSheet, zoom: 12 },
  'missile.png': { build: buildMissileSheet, zoom: 14 },
  'player-f14-night.png': { build: buildPlayerF14NightSheet, zoom: 8 },
  'player-f14-roll.png': { build: buildPlayerF14RollSheet, zoom: 8 },
};

// One sheet per (livery, aspect, day|night). Enumerated rather than
// hand-listed so adding a livery to palettes.js ships its art without editing
// this file; the file name is `enemy-<livery>-<headon|rear>[-night].png` and
// the silhouette family is looked up from the livery inside the generator.
//
// R6: the NIGHT half is new. `if (detail && !night)` in
// src/entities/enemySprite.js meant every stage-3 enemy fell through to the
// procedural fallback, so R4's headline gap 1 was only ever closed for
// daylight (judging/R5/report.md, "what nobody had looked at").
for (const livery of ENEMY_SHEET_LIVERIES) {
  for (const aspect of ENEMY_SHEET_ASPECTS) {
    for (const night of ENEMY_SHEET_NIGHT) {
      const suffix = aspect === 'headOn' ? 'head' : 'rear';
      SHEETS[`enemy-${livery}-${suffix}${night ? '-night' : ''}.png`] = {
        build: () => buildEnemySheet(livery, aspect, night),
        zoom: 10,
      };
    }
  }
}

const only = process.argv[2];
for (const [name, { build, zoom }] of Object.entries(SHEETS)) {
  if (only && name !== only) continue;
  const sheet = build();
  const outPath = OUT_DIR + name;
  sheet.writeFile(outPath);
  const z = sheet.zoom(zoom);
  z.writeFile(ZOOM_DIR + name.replace('.png', `.zoom${zoom}x.png`));
  const colours = sheet.countColours();
  console.log(`${name}: ${sheet.width}x${sheet.height}, ${colours.size} unique colours -> ${outPath}`);
}

// ---------------------------------------------------------------------------
// Generated palette module for the FAR LOD.
//
// src/entities/enemySprite.js draws the 16x8 far-field sprite procedurally and
// used to carry its OWN copy of the livery table. The two had already drifted
// by R5 (camo's highlight was #8cad31 in one and #5a3a19 in the other), and a
// drifted fallback palette is invisible precisely because the fallback only
// runs in the conditions nobody captures. Emitting the table from the same
// ENEMY_LIVERIES the sheets are drawn from makes drift impossible rather than
// merely discouraged. Regenerate with `node tools/art/build.js`.
// ---------------------------------------------------------------------------
const paletteModule =
  '// GENERATED by tools/art/build.js from tools/art/palettes.js ENEMY_LIVERIES.\n' +
  '// DO NOT EDIT. Edit the palette table and re-run the build.\n' +
  '// This is the single source for both the authored enemy sheets and the\n' +
  '// procedural far-LOD textures, so the two cannot drift apart in colour.\n' +
  'export const ENEMY_LIVERIES = ' +
  JSON.stringify(ENEMY_LIVERIES, null, 2) +
  ';\n';
const palettePath = OUT_DIR + 'enemy-palettes.generated.js';
writeFileSync(palettePath, paletteModule);
console.log(`enemy-palettes.generated.js: ${Object.keys(ENEMY_LIVERIES).length} liveries -> ${palettePath}`);
